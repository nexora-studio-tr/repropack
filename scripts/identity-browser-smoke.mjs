import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { createApp } from '../src/server.ts';

const directory = await mkdtemp(join(tmpdir(), 'repropack-identity-browser-'));
const screenshots = fileURLToPath(new URL('../artifacts/identity-browser/', import.meta.url));
await mkdir(screenshots, { recursive: true });
const app = await createApp(directory);
let browser;
try {
  app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening');
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  try { browser = await chromium.launch({ headless: true }); }
  catch (error) { if (process.platform !== 'win32') throw error; browser = await chromium.launch({ headless: true, channel: 'msedge' }); }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading', { name: 'Create the first workspace' }).waitFor();
  await page.screenshot({ path: join(screenshots, 'setup-desktop.png'), fullPage: true });
  await page.getByLabel('Local setup key', { exact: true }).fill((await readFile(app.bootstrapPath, 'utf8')).trim());
  await page.getByLabel('Your name', { exact: true }).fill('Ada Research');
  await page.getByLabel('Email', { exact: true }).fill('ada@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-only browser passphrase for Ada');
  await page.getByLabel('Team name', { exact: true }).fill('Failure laboratory');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByRole('button', { name: /Reduce scenario/ }).waitFor();
  assert.equal(await page.evaluate(() => document.cookie), '', 'HttpOnly session is not available to JavaScript');
  assert.equal(await page.evaluate(() => [...Array(localStorage.length)].map((_, index) => localStorage.key(index)).filter(key => /token|session|csrf|password/i.test(key ?? '')).length), 0);
  const teamA = await page.getByRole('combobox', { name: 'Active team', exact: true }).inputValue();
  await page.getByRole('button', { name: 'Account & team' }).click();
  await page.getByRole('heading', { name: 'Team access', exact: true }).waitFor();
  await page.getByLabel('Teammate email', { exact: true }).fill('grace@example.test');
  await page.getByLabel('Role', { exact: true }).selectOption('viewer');
  await page.getByRole('button', { name: /Create invitation/ }).click();
  const invitation = await page.getByLabel('Invitation link — shown only now', { exact: true }).inputValue();
  assert.ok(new URL(invitation).hash.startsWith('#invite='));
  await page.getByRole('button', { name: 'Hide invitation link', exact: true }).click();
  await page.screenshot({ path: join(screenshots, 'team-desktop.png'), fullPage: true });
  const inviteeContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const invitee = await inviteeContext.newPage(); invitee.on('pageerror', error => errors.push(error.message));
  await invitee.goto(invitation); await invitee.getByRole('heading', { name: 'Join the team', exact: true }).waitFor();
  await invitee.getByLabel('Your name', { exact: true }).fill('Grace Reader');
  await invitee.getByLabel('Password', { exact: true }).fill('test-only browser passphrase for Grace');
  await invitee.getByRole('button', { name: /Accept invitation/ }).click();
  await invitee.getByRole('button', { name: /Read-only access/ }).waitFor(); assert.equal(await invitee.getByRole('button', { name: /Read-only access/ }).isDisabled(), true);
  assert.equal(await invitee.evaluate(() => location.hash), '');
  await invitee.getByRole('button', { name: 'TR', exact: true }).click();
  assert.ok(await invitee.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await invitee.screenshot({ path: join(screenshots, 'viewer-mobile-tr.png'), fullPage: true });
  await page.getByLabel('New team name', { exact: true }).fill('Isolated experiments');
  await page.getByRole('button', { name: /Create a team/ }).click();
  await page.getByRole('combobox', { name: 'Active team', exact: true }).selectOption({ label: 'Isolated experiments' });
  await page.getByText('Your first reproduction starts here.', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'Active team', exact: true }).selectOption(teamA);
  await page.getByRole('button', { name: 'Account & team' }).click();
  await page.getByText('Grace Reader', { exact: true }).waitFor();
  const graceRow = page.locator('.member-row').filter({ hasText: 'grace@example.test' });
  await graceRow.getByRole('combobox').selectOption('member'); await graceRow.getByRole('button', { name: 'Save role', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Changes saved' }).waitFor();
  assert.equal(await graceRow.getByRole('combobox').inputValue(), 'member');
  await invitee.reload(); await invitee.getByRole('heading', { name: 'Giriş yap', exact: true }).waitFor();
  await invitee.getByLabel('E-posta', { exact: true }).fill('grace@example.test');
  await invitee.getByLabel('Parola', { exact: true }).fill('test-only browser passphrase for Grace');
  await invitee.getByRole('button', { name: 'Giriş yap', exact: true }).click();
  await invitee.getByRole('button', { name: /Senaryoyu küçült/ }).waitFor(); assert.equal(await invitee.getByRole('button', { name: /Senaryoyu küçült/ }).isEnabled(), true);
  await page.getByRole('button', { name: 'TR', exact: true }).click(); await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(screenshots, 'team-mobile-tr.png'), fullPage: true });
  await page.getByRole('button', { name: 'Çıkış yap', exact: true }).click();
  await page.getByRole('heading', { name: 'Giriş yap', exact: true }).waitFor();
  assert.equal((await page.request.get(`${origin}/api/runs`)).status(), 401);
  assert.deepEqual(errors, []);
  console.log('Identity browser gate passed: setup, HttpOnly session, invitation, viewer controls, team isolation UI, role invalidation/re-login, logout, EN/TR mobile.');
} finally { await browser?.close(); await app.dispose(); await rm(directory, { recursive: true, force: true }); }
