import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { createApp } from '../src/server.ts';

const directory = await mkdtemp(join(tmpdir(), 'repropack-browser-'));
const screenshots = fileURLToPath(new URL('../artifacts/browser-smoke/', import.meta.url));
await mkdir(screenshots, { recursive: true });
const app = await createApp(directory);
let browser;
try {
  app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening');
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  const options = { headless: true };
  if (process.env.REPROPACK_BROWSER === 'edge') options.channel = 'msedge';
  try { browser = await chromium.launch(options); }
  catch (error) {
    if (process.platform !== 'win32' || options.channel) throw error;
    browser = await chromium.launch({ headless: true, channel: 'msedge' });
  }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading', { name: 'Create the first workspace' }).waitFor();
  await page.getByLabel('Local setup key', { exact: true }).fill((await readFile(app.bootstrapPath, 'utf8')).trim());
  await page.getByLabel('Your name', { exact: true }).fill('Browser owner');
  await page.getByLabel('Email', { exact: true }).fill('browser-owner@example.test');
  await page.getByLabel('Password', { exact: true }).fill('browser-only correct horse battery staple');
  await page.getByLabel('Team name', { exact: true }).fill('Browser laboratory');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByRole('button', { name: /Reduce scenario/ }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /Reduce scenario/ }).waitFor();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement?.className), 'skip-link');
  await page.getByRole('button', { name: /Reduce scenario/ }).click();
  await page.getByText('Exact failure preserved in fresh replays.').waitFor({ timeout: 30_000 });
  const runs = await (await page.request.get(`${origin}/api/runs`)).json();
  assert.equal(runs.length, 1); assert.equal(runs[0].reducedSteps, 5);
  await page.getByRole('button', { name: 'Check demo fix' }).click();
  await page.getByText('Built-in demo fix: expected success observed in 3 fresh trials.').waitFor();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: /Export capsule/ }).click();
  const download = await downloadEvent;
  await download.saveAs(join(screenshots, 'exported-capsule.json'));
  await page.getByRole('button', { name: /Coupon disappears after quantity change/ }).click();
  await page.getByText('Exact failure preserved in fresh replays.').waitFor();
  assert.equal(await page.locator('.steps li.kept').count(), 5);
  assert.equal(await page.locator('.steps li.removed').count(), 11);
  await page.screenshot({ path: join(screenshots, 'desktop.png'), fullPage: true });
  await page.locator('.source-editor > summary').click();
  await page.getByLabel(/Edit or import a schema/).fill('{');
  await page.getByRole('button', { name: /Reduce scenario/ }).click();
  await page.getByRole('alert').waitFor();
  assert.match(await page.getByRole('alert').innerText(), /valid JSON/);
  await page.getByRole('button', { name: 'New reproduction' }).click();
  await page.getByRole('button', { name: /Coupon disappears after quantity change/ }).click();
  await page.getByText('Exact failure preserved in fresh replays.').waitFor();
  await page.getByRole('button', { name: 'TR', exact: true }).click();
  await page.getByRole('heading', { name: 'Hatayı anlamayı kolaylaştır.' }).waitFor();
  if (await page.locator('.source-editor').evaluate(element => element.open)) await page.locator('.source-editor > summary').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(screenshots, 'mobile-tr.png'), fullPage: true });
  const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(element => element.getBoundingClientRect().right > window.innerWidth + 1 && getComputedStyle(element).display !== 'none').slice(0, 12).map(element => ({ tag: element.tagName, className: element.className, right: Math.round(element.getBoundingClientRect().right) })));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `No horizontal overflow on mobile: ${JSON.stringify(overflow)}`);
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.getByRole('combobox', { name: 'Application', exact: true }).selectOption('postgres');
  await page.locator('.capsule-title').filter({ hasText: 'PostgreSQL cart:' }).waitFor();
  await page.getByText('Trusted local execution', { exact: true }).waitFor();
  await page.getByRole('button', { name: /Reduce scenario/ }).click();
  await page.getByText('Exact failure preserved in fresh replays.').waitFor({ timeout: 120_000 });
  const pgRuns = await (await page.request.get(`${origin}/api/runs`)).json();
  const pgRun = pgRuns.find(run => run.title.startsWith('PostgreSQL cart:'));
  assert.equal(pgRun.reducedSteps, 3);
  await page.getByText('4 selected rows · 1 masked fields').waitFor();
  await page.getByRole('button', { name: 'Check configured fix' }).click();
  await page.getByText('Configured fix: expected success observed in 3 fresh trials.').waitFor({ timeout: 45_000 });
  const report = await (await page.request.get(`${origin}/api/runs/${pgRun.id}/report`)).json();
  assert.match(report.environment.postgresVersion, /PostgreSQL 18\./);
  assert.equal(report.environment.redactedCells, 1);
  assert.equal(report.environment.execution.kind, 'trusted-native');
  assert.equal(report.verification.adapter, 'configured-node-module');
  await page.screenshot({ path: join(screenshots, 'postgres-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'TR', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'PostgreSQL evidence fits the mobile viewport');
  await page.screenshot({ path: join(screenshots, 'postgres-mobile-tr.png'), fullPage: true });
  assert.deepEqual(errors, [], 'No uncaught browser errors');
  console.log('Browser smoke passed: HTTP (16 → 5), actual PostgreSQL/Node process (12 → 3), both fixes, snapshot evidence, export, keyboard, history, invalid JSON, Turkish UI and 390px layouts.');
  console.log(`Screenshots: ${screenshots}`);
} finally {
  await browser?.close();
  await app.dispose();
  await rm(directory, { recursive: true, force: true });
}
